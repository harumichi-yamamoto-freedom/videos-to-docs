/** 交互反復の合成に使う相槌 (これらは「反復側」なので、実発話プールからは除く) */
const AIZUCHI = new Set([
    'はい', 'ええ', 'うん', 'あー', 'あ', 'えー', 'えっと', 'うーん', 'そうですね', 'なるほど',
    'はいはい', 'そうですか', 'ありがとうございます', 'お願いします', '承知しました',
    '分かりました', 'かしこまりました', 'わかりました',
]);

const stripPunctuation = (unit: string): string =>
    unit.replace(/[。．.、，,！？!?「」『』（）()［］\[\]〜~・:：;；…\s]/g, '');

/**
 * 崩壊 3: 反復が実発話と**交互**に出る型。
 * 正常本文から相槌と重複を除いた実発話プールを作り、その 1 文ごとに `はい。ええ。` を挟む。
 * 🔴 これで**同一ユニットは 1 度も連続しない** (最長連続 1) ため G3 は素通りし、
 * 圧縮率も 3.76 と閾値 8.0 の内側に収まるので G5 も素通りする。**捕まえられるのは G4 (ユニーク率 0.336) だけ。**
 * G3 と G4 の片方だけにしてはいけない、という設計判断の証人。
 */
export const buildAlternatingRepetitionText = (source: string): string => {
    const seen = new Set<string>();
    const pool: string[] = [];
    for (const sentence of source.split(/[。．、\r\n]+/)) {
        const trimmed = sentence.trim();
        const normalized = stripPunctuation(trimmed);
        if (normalized.length === 0 || AIZUCHI.has(normalized) || seen.has(normalized)) continue;
        seen.add(normalized);
        pool.push(trimmed);
    }
    return pool.map((sentence) => `はい。ええ。${sentence}。`).join('');
};

