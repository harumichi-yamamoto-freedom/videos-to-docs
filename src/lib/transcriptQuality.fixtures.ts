import type { ChunkResult, TranscriptAnnotation } from './transcriptQuality';

/** 話者分離＋単語タイムスタンプ有効時の注釈を、指定のカバレッジまで等間隔に敷く */
export const makeAnnotations = (
    audioSec: number,
    coverage: number,
    speakers: Array<string | null> = ['spk:0', 'spk:1'],
    count = 20,
): TranscriptAnnotation[] => {
    const lastEnd = audioSec * coverage;
    const step = lastEnd / count;
    return Array.from({ length: count }, (_, index) => ({
        text: `語${index}`,
        startOffsetSec: Number((index * step).toFixed(3)),
        endOffsetSec: Number(((index + 1) * step).toFixed(3)),
        speaker: speakers[index % speakers.length],
    }));
};

/** ChunkResult を組み立てる。既定は「話者2名・カバレッジ 0.99・status completed」の健全な形 */
export const makeChunk = (text: string, overrides: Partial<ChunkResult> = {}): ChunkResult => {
    const audioSec = overrides.audioSec ?? 600;
    return {
        status: 'completed',
        text,
        audioSec,
        speechSec: audioSec * 0.8,
        // 🔴 既定は「音声全体が発話」= G6 (最長穴) にとって最も厳しい形。
        //    無音を混ぜて穴を隠さない。注釈のカバレッジを下げれば必ず穴として現れる。
        speechIntervals: [[0, audioSec]],
        annotations: makeAnnotations(audioSec, 0.99),
        ...overrides,
    };
};

